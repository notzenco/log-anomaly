"""Command line interface: ``log-anomaly download|synth|train|score|evaluate``.

The score command is a triage tool, not a verdict: it prints the most
anomalous events in a log file together with the features that drove each
score, so an analyst can decide whether the event matters without reopening
the raw log.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from log_anomaly.data import DATASET_NAMES, fetch_all, fetch_dataset, get_spec
from log_anomaly.data.synthetic import SyntheticConfig, write_corpus
from log_anomaly.evaluation import evaluate_all, load_labels, results_to_frame
from log_anomaly.features import FEATURE_NAMES, extract_features
from log_anomaly.models import MODEL_NAMES, TrainedModel, fit_model
from log_anomaly.parsing import parse_file

SYNTHETIC_MARKER = "# SYNTHETIC LOG"


def _is_synthetic(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            return handle.readline().startswith(SYNTHETIC_MARKER)
    except OSError:
        return False


def _parse_events(path: Path, anchor_year: int, log_format: str) -> pd.DataFrame:
    events, stats = parse_file(path, log_format=log_format, anchor_year=anchor_year)
    if events.empty:
        raise ValueError(f"no events could be parsed from {path} (stats: {stats})")
    return events


def _add_log_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--anchor-year",
        type=int,
        default=2024,
        help="year for syslog timestamps, which carry no year (default: 2024)",
    )
    parser.add_argument(
        "--format",
        choices=["auto", "syslog", "proxifier"],
        default="auto",
        help="log format (default: auto-detect)",
    )


def _warn_synthetic(path: Path) -> bool:
    synthetic = _is_synthetic(path)
    if synthetic:
        print(f"note: {path} is a SYNTHETIC corpus generated by log-anomaly", file=sys.stderr)
    return synthetic


def cmd_download(args: argparse.Namespace) -> int:
    dest = Path(args.dest)
    if args.dataset == "all":
        paths = fetch_all(dest, force=args.force)
    else:
        paths = {args.dataset: fetch_dataset(args.dataset, dest, force=args.force)}
    for name, path in sorted(paths.items()):
        print(f"[{name}] {path}")
        print(f"  {get_spec(name).attribution()}")
    return 0


def cmd_synth(args: argparse.Namespace) -> int:
    config = SyntheticConfig(days=args.days, hosts=args.hosts, users=args.users, seed=args.seed)
    out = Path(args.out)
    summary = write_corpus(config, out / "synth.log", out / "labels.csv", out / "meta.json")
    print(f"SYNTHETIC corpus written to {out} (not real host telemetry)")
    print(json.dumps(summary, indent=2))
    return 0


def cmd_train(args: argparse.Namespace) -> int:
    log_path = Path(args.log)
    synthetic = _warn_synthetic(log_path)
    events = _parse_events(log_path, args.anchor_year, args.format)
    feature_set = extract_features(events)
    trained = fit_model(
        args.model,
        feature_set.features.to_numpy(dtype=np.float64),
        feature_set.feature_names,
        metadata={
            "model": args.model,
            "trained_on": str(log_path),
            "synthetic": synthetic,
            "n_events": int(len(events)),
            "span_start": str(feature_set.events["ts"].min()),
            "span_end": str(feature_set.events["ts"].max()),
            "anchor_year": args.anchor_year,
            "availability": feature_set.availability,
            "trained_at": datetime.now(UTC).isoformat(),
        },
    )
    target = trained.save(Path(args.out))
    print(f"trained {args.model} on {len(events)} events from {log_path}")
    print(f"model written to {target}")
    return 0


def _format_reason(explanation: list[tuple[str, float]]) -> str:
    parts = [f"{name}={value:.3g}" for name, value in explanation if value > 0]
    return ", ".join(parts) if parts else "no single feature dominates"


def cmd_score(args: argparse.Namespace) -> int:
    log_path = Path(args.logfile)
    _warn_synthetic(log_path)
    trained = TrainedModel.load(Path(args.model))
    if tuple(trained.feature_names) != tuple(FEATURE_NAMES):
        raise ValueError(
            "the saved model was trained on a different feature set; retrain it "
            f"(model has {len(trained.feature_names)} features, this build has "
            f"{len(FEATURE_NAMES)})"
        )
    events = _parse_events(log_path, args.anchor_year, args.format)
    feature_set = extract_features(events)
    matrix = feature_set.features.to_numpy(dtype=np.float64)
    scores = trained.score(matrix)

    order = np.argsort(scores)[::-1]
    if args.threshold is not None:
        order = order[scores[order] >= args.threshold]
    shown = order[: args.top_k]

    # explanations only for the rows we print: occlusion is per-feature work
    explanations = trained.explain(matrix[shown], top_k=args.explain_k) if len(shown) else []
    ordered_events = feature_set.events

    print(f"# {len(shown)} alerts from {log_path} (model: {trained.model.name})")
    for rank, (position, explanation) in enumerate(zip(shown, explanations, strict=True), 1):
        event = ordered_events.iloc[position]
        user = event["user"] if pd.notna(event["user"]) else "-"
        source = event["src_ip"] if pd.notna(event["src_ip"]) else "-"
        print(
            f"{rank:>3}  score={scores[position]:.4g}  {event['ts']}  "
            f"{event['host']}  {event['event_type']}  user={user}  src={source}"
        )
        print(f"     reason: {_format_reason(explanation)}")
        raw = str(event["raw"]).strip() if pd.notna(event["raw"]) else ""
        if raw:
            print(f"     log: {raw[:160]}")
    if args.threshold is not None and len(order) > len(shown):
        print(f"# ... and {len(order) - len(shown)} more events at or above the threshold")
    return 0


class _JsonEncoder(json.JSONEncoder):
    def default(self, obj: Any) -> Any:
        if isinstance(obj, np.integer):
            return int(obj)
        if isinstance(obj, np.floating):
            return float(obj)
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        return super().default(obj)


def cmd_evaluate(args: argparse.Namespace) -> int:
    log_path = Path(args.log)
    if args.corpus is None:
        args.corpus = log_path.stem
    synthetic = _warn_synthetic(log_path)
    events = _parse_events(log_path, args.anchor_year, args.format)
    labels = load_labels(Path(args.labels))
    models = [name.strip() for name in args.models.split(",") if name.strip()]
    unknown = set(models) - set(MODEL_NAMES)
    if unknown:
        raise ValueError(f"unknown model(s) {sorted(unknown)}; available: {', '.join(MODEL_NAMES)}")
    excludes = tuple(name.strip() for name in args.exclude_types.split(",") if name.strip())

    results = evaluate_all(
        events,
        labels,
        corpus=args.corpus,
        models=models,
        exclude_types=excludes,
        clean_training=args.clean_training,
        alert_budget=args.alert_budget,
    )
    frame = results_to_frame(results)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    frame.to_csv(out / "results.csv", index=False)
    payload = {
        "corpus": args.corpus,
        "synthetic": synthetic,
        "log": str(log_path),
        "labels": str(args.labels),
        "results": [result.to_dict() for result in results],
    }
    (out / "results.json").write_text(
        json.dumps(payload, indent=2, cls=_JsonEncoder) + "\n", encoding="utf-8"
    )
    label = "SYNTHETIC" if synthetic else "labelled"
    print(f"# evaluation on {args.corpus} ({label} corpus)")
    print(frame.to_string(index=False))
    print(f"wrote {out / 'results.csv'} and {out / 'results.json'}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="log-anomaly",
        description="Host-based log anomaly detection with a time-aware evaluation.",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    download = sub.add_parser("download", help="fetch and checksum-verify a public dataset")
    download.add_argument("--dataset", choices=[*DATASET_NAMES, "all"], default="all")
    download.add_argument("--dest", default="data/raw", help="where raw data goes (git-ignored)")
    download.add_argument("--force", action="store_true", help="refetch even if verified")
    download.set_defaults(func=cmd_download)

    synth = sub.add_parser("synth", help="generate the labelled SYNTHETIC corpus")
    synth.add_argument("--out", default="data/synthetic")
    synth.add_argument("--days", type=int, default=SyntheticConfig().days)
    synth.add_argument("--hosts", type=int, default=SyntheticConfig().hosts)
    synth.add_argument("--users", type=int, default=SyntheticConfig().users)
    synth.add_argument("--seed", type=int, default=SyntheticConfig().seed)
    synth.set_defaults(func=cmd_synth)

    train = sub.add_parser("train", help="fit a model on a log file")
    train.add_argument("--log", required=True)
    train.add_argument("--model", choices=MODEL_NAMES, default="iforest")
    train.add_argument("--out", required=True, help="path for the saved model (.joblib)")
    _add_log_arguments(train)
    train.set_defaults(func=cmd_train)

    score = sub.add_parser("score", help="print the most anomalous events in a log file")
    score.add_argument("logfile")
    score.add_argument("--model", required=True, help="path to a model saved by train")
    score.add_argument("--top-k", type=int, default=20, help="alerts to print (default: 20)")
    score.add_argument(
        "--threshold", type=float, default=None, help="only print events at or above this score"
    )
    score.add_argument(
        "--explain-k", type=int, default=3, help="contributing features per alert (default: 3)"
    )
    _add_log_arguments(score)
    score.set_defaults(func=cmd_score)

    evaluate = sub.add_parser("evaluate", help="run the time-split evaluation on labelled data")
    evaluate.add_argument("--log", required=True)
    evaluate.add_argument("--labels", required=True)
    evaluate.add_argument("--out", default="reports")
    evaluate.add_argument(
        "--corpus", default=None, help="corpus name in the results (default: log file stem)"
    )
    evaluate.add_argument("--models", default=",".join(MODEL_NAMES))
    evaluate.add_argument(
        "--exclude-types", default="", help="attack types left out of the measurement only"
    )
    evaluate.add_argument(
        "--clean-training",
        action="store_true",
        help="oracle ablation: remove attack events from training",
    )
    evaluate.add_argument("--alert-budget", type=float, default=20.0)
    _add_log_arguments(evaluate)
    evaluate.set_defaults(func=cmd_evaluate)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
